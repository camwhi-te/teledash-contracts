// Generates everything consumers use from schemas/: bundled JSON schemas,
// TypeScript types + registry, and PHP DTOs. Output is committed so consumers
// never need to run codegen; CI fails if it is stale.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { compile } from 'json-schema-to-typescript'
import { type Json, loadMessages, type MessageSchema, ROOT, readJson, SCHEMAS } from './lib'

const BANNER = 'GENERATED by scripts/generate.ts from schemas/. Do not edit.'
const GEN_SCHEMAS = join(ROOT, 'generated', 'schemas')
const GEN_TS = join(ROOT, 'src', 'generated')
const GEN_PHP = join(ROOT, 'php', 'src', 'Generated')

for (const d of [join(ROOT, 'generated'), GEN_TS, GEN_PHP]) rmSync(d, { recursive: true, force: true })
for (const d of [GEN_SCHEMAS, GEN_TS, join(GEN_PHP, 'Messages')]) mkdirSync(d, { recursive: true })

const messages = loadMessages()
const envelope = readJson(join(SCHEMAS, 'envelope.v1.json'))
const fileName = (m: MessageSchema) => `${m.type}.v${m.version}.json`

writeFileSync(join(GEN_SCHEMAS, 'envelope.v1.json'), `${JSON.stringify(envelope, null, 2)}\n`)
for (const m of messages) writeFileSync(join(GEN_SCHEMAS, fileName(m)), `${JSON.stringify(m.bundled, null, 2)}\n`)

// ---- TypeScript -------------------------------------------------------------

const tsTypes: string[] = [`// ${BANNER}`, '']
for (const m of messages) {
  const { $id, $schema, ...schema } = m.bundled
  const ts = await compile({ ...schema, title: m.className }, m.className, {
    bannerComment: '',
    additionalProperties: false,
    format: false,
  })
  tsTypes.push(ts.trim(), '')
}
tsTypes.push('/** Payload type for each `type@version`. */', 'export interface MessagePayloads {')
for (const m of messages) tsTypes.push(`  '${m.type}@${m.version}': ${m.className}`)
tsTypes.push('}', '')
tsTypes.push(
  `export type CommandKey = ${
    messages
      .filter(m => m.kind === 'command')
      .map(m => `'${m.type}@${m.version}'`)
      .join(' | ') || 'never'
  }`,
)
tsTypes.push(
  `export type EventKey = ${
    messages
      .filter(m => m.kind === 'event')
      .map(m => `'${m.type}@${m.version}'`)
      .join(' | ') || 'never'
  }`,
)
writeFileSync(join(GEN_TS, 'types.ts'), `${tsTypes.join('\n')}\n`)

const reg: string[] = [`// ${BANNER}`, '']
reg.push(`import envelope from '../../generated/schemas/envelope.v1.json' with { type: 'json' }`)
messages.forEach((m, i) => {
  reg.push(`import s${i} from '../../generated/schemas/${fileName(m)}' with { type: 'json' }`)
})
reg.push('', 'export const envelopeSchema = envelope', '')
reg.push('export const catalogue = [')
messages.forEach((m, i) => {
  reg.push(`  { type: '${m.type}', version: ${m.version}, kind: '${m.kind}', schema: s${i} },`)
})
reg.push('] as const', '')
writeFileSync(join(GEN_TS, 'registry.ts'), `${reg.join('\n')}\n`)

// ---- PHP --------------------------------------------------------------------

function phpType(s: Json, required: boolean): { decl: string; nullable: boolean } {
  // oneOf [X, {type: null}] is "X or null"
  if (Array.isArray(s.oneOf) && !s.type) {
    const typed = s.oneOf.flatMap((o: Json) => (Array.isArray(o.type) ? o.type : [o.type])).filter(Boolean)
    s = { ...s, type: [...new Set(typed)] }
  }
  let types: string[] = Array.isArray(s.type) ? s.type : [s.type ?? 'mixed']
  const nullable = types.includes('null') || !required
  types = types.filter(t => t !== 'null')
  const map: Record<string, string> = {
    string: 'string',
    integer: 'int',
    number: 'float',
    boolean: 'bool',
    object: 'array',
    array: 'array',
  }
  const php = types.length === 1 && map[types[0]] ? map[types[0]] : 'mixed'
  return { decl: php === 'mixed' ? 'mixed' : `${nullable ? '?' : ''}${php}`, nullable }
}

function phpClass(m: MessageSchema): string {
  const props = m.bundled.properties ?? {}
  const required: string[] = m.bundled.required ?? []
  // required params first so optional ones can default to null
  const names = Object.keys(props).sort((a, b) => Number(required.includes(b)) - Number(required.includes(a)))
  const params = names.map(n => {
    const { decl, nullable } = phpType(props[n], required.includes(n))
    const doc = props[n].description ? `        /** ${String(props[n].description).replace(/\*\//g, '')} */\n` : ''
    return `${doc}        public ${decl} $${n}${nullable && !required.includes(n) ? ' = null' : ''},`
  })
  const from = names.map(n => `            ${n}: $data['${n}']${required.includes(n) ? '' : ' ?? null'},`)
  const required_ = names.filter(n => required.includes(n))
  const optional = names.filter(n => !required.includes(n))
  // required fields are always present (null included); optional ones are left out when null
  const to = [
    ...required_.map(n => `            '${n}' => $this->${n},`),
    ...optional.map(n => `            ...($this->${n} === null ? [] : ['${n}' => $this->${n}]),`),
  ]
  return `<?php

// ${BANNER}

declare(strict_types=1);

namespace Teledash\\Contracts\\Generated\\Messages;

use Teledash\\Contracts\\Message;

/**
 * ${m.type} v${m.version} (${m.kind})${m.bundled.description ? `\n * ${m.bundled.description}` : ''}
 */
final readonly class ${m.className} implements Message
{
    public const TYPE = '${m.type}';
    public const VERSION = ${m.version};
    public const KIND = '${m.kind}';

    public function __construct(
${params.join('\n')}
    ) {}

    public static function fromArray(array $data): self
    {
        return new self(
${from.join('\n')}
        );
    }

    public function toArray(): array
    {
        return [
${to.join('\n')}
        ];
    }

    public function type(): string
    {
        return self::TYPE;
    }

    public function version(): int
    {
        return self::VERSION;
    }
}
`
}

for (const m of messages) writeFileSync(join(GEN_PHP, 'Messages', `${m.className}.php`), phpClass(m))

const cat = messages.map(
  m =>
    `        '${m.type}@${m.version}' => ['kind' => '${m.kind}', 'class' => Messages\\${m.className}::class, 'schema' => '${fileName(m)}'],`,
)
writeFileSync(
  join(GEN_PHP, 'Catalogue.php'),
  `<?php

// ${BANNER}

declare(strict_types=1);

namespace Teledash\\Contracts\\Generated;

final class Catalogue
{
    /** @var array<string, array{kind: string, class: class-string, schema: string}> */
    public const MESSAGES = [
${cat.join('\n')}
    ];
}
`,
)

console.log(`generated ${messages.length} message schemas (${messages.map(m => `${m.type}@${m.version}`).join(', ')})`)
